import assert from 'node:assert/strict'
import {readFile} from 'node:fs/promises'
const x=JSON.parse(await readFile(new URL('../../exports/blue-carousel/timeline.json',import.meta.url)))
assert.equal(x.width/x.height,16/3);assert.equal(x.frames%2,0)
assert.equal(x.segments[0].name,'n-bubble');assert.equal(x.segments.at(-1).name,'n-flag')
assert(x.segments.every(s=>!s.name.includes('skibidi')))
const flag=x.segments.find(s=>s.kind==='flag');assert(Math.abs(flag.end-flag.start-3)<1e-9)
const frames=x.frameInfo.filter(f=>f.kind==='flag');assert.equal(frames.length,180)
assert.equal(frames[0].sourceFrame,0);assert.equal(frames.at(-1).sourceFrame,179)
assert.deepEqual(frames.map(f=>f.sourceFrame),Array.from({length:180},(_,i)=>i))
const random=x.segments.filter(s=>s.kind==='random'),dur=random.map(s=>s.end-s.start)
assert(dur[0]>.4&&Math.min(...dur)<.06&&dur.at(-1)<.06)
assert.deepEqual(x.segments.slice(1,4).map(s=>s.name),['facepalm','identification-card','partying-face'])
assert.deepEqual(x.segments.filter(s=>s.kind==='ending').map(s=>s.name),['coffin','screaming-face','technologist-bust','family'])
const ending=x.segments.filter(s=>s.kind==='ending')
for(let i=1;i<ending.length;i++)assert(ending[i].end-ending[i].start>ending[i-1].end-ending[i-1].start)
const palm=x.frameInfo.filter(f=>f.name==='facepalm'),laptop=x.frameInfo.filter(f=>f.name==='technologist-bust')
assert.equal(palm[0].sourceFrame,124);assert(palm.at(-1).sourceFrame>=170)
assert.equal(laptop[0].sourceFrame,64);assert(laptop.at(-1).sourceFrame>=98)
for(let i=1;i<random.length;i++)assert.notEqual(random[i].name,random[i-1].name)
console.log('Pop → slow/fast/slow cuts → exactly one native flag cycle → exit; no Skibidi, even video frame count')
